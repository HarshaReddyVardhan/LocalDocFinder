def test_pdf_text_pages_and_image_ocr(tmp_path):
    img = tmp_path / "fig.png"
    _text_image("Quarterly revenue forecast", img)
    pdf = tmp_path / "doc.pdf"
    doc = pymupdf.open()
    p1 = doc.new_page()
    p1.insert_text((72, 72), "Introduction to the budget process")
    p2 = doc.new_page()
    p2.insert_text((72, 72), "Appendix with a diagram shown below in this document")
    p2.insert_image(pymupdf.Rect(72, 100, 472, 300), filename=str(img))
    doc.save(str(pdf))
    chunks = extract(str(pdf))
    assert any(c.page == 1 and "budget" in c.text for c in chunks)
    fig = [c for c in chunks if c.kind == "image"]
    assert fig and fig[0].page == 2 and "revenue" in fig[0].text.lower()


def test_scanned_pdf_page_is_ocrd(tmp_path):
    img = tmp_path / "scan.png"
    _text_image("Scanned contract clause seven", img)
    pdf = tmp_path / "scan.pdf"
    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_image(page.rect, filename=str(img))
    doc.save(str(pdf))
    chunks = extract(str(pdf))
    assert any("contract" in c.text.lower() and c.page == 1 for c in chunks)


def test_docx_headings_and_image(tmp_path):
    import docx
    img = tmp_path / "pic.png"
    _text_image("Network topology diagram", img)
    d = docx.Document()
    d.add_heading("Design", level=1)
    d.add_paragraph("We use a hub and spoke layout.")
    d.add_heading("Details", level=2)
    d.add_paragraph("Latency matters most.")
    d.add_picture(str(img))
    out = tmp_path / "a.docx"
    d.save(str(out))
    chunks = extract(str(out))
    assert any(c.symbol == "Design > Details" for c in chunks)
    assert any(c.kind == "image" and "topology" in c.text.lower() for c in chunks)


def test_pptx_slides(tmp_path):
    from pptx import Presentation
    prs = Presentation()
    s = prs.slides.add_slide(prs.slide_layouts[1])
    s.shapes.title.text = "Roadmap"
    s.placeholders[1].text = "Ship the indexer"
    out = tmp_path / "a.pptx"
    prs.save(str(out))
    chunks = extract(str(out))
    assert chunks[0].page == 1 and "indexer" in chunks[0].text


