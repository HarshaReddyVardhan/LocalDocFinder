import pymupdf
import pytest
from PIL import Image, ImageDraw, ImageFont

import indexer_config as cfg
from extract import extract, ExtractError

PY_SRC = '''import os
import sys

MAX = 10


def add(a, b):
    """Add two numbers."""
    return a + b


class PaymentService:
    def charge(self, amount):
        return amount * 2

    def refund(self, amount):
        return -amount
'''


def _text_image(text: str, path) -> None:
    img = Image.new("RGB", (900, 260), "white")
    try:
        font = ImageFont.truetype("arial.ttf", 48)
    except Exception:
        font = None
    ImageDraw.Draw(img).text((30, 90), text, fill="black", font=font)
    img.save(path)


def test_python_symbols_and_outline(make):
    chunks = extract(make("a.py", PY_SRC))
    kinds = {c.kind for c in chunks}
    assert "outline" in kinds and "code" in kinds
    outline = next(c for c in chunks if c.kind == "outline")
    assert "PaymentService" in outline.text and "import os" in outline.text
    joined = "\n".join(c.text for c in chunks if c.kind == "code")
    assert "def charge" in joined and "def add" in joined


def test_large_class_split_into_methods(make):
    methods = "\n".join(f"    def m{i}(self):\n        return {i} * 'x' * 20\n" for i in range(400))
    chunks = extract(make("big.py", "class Big:\n    '''doc'''\n\n" + methods))
    symbols = {c.symbol for c in chunks}
    assert any(s.startswith("Big.m") for s in symbols)
    assert all(len(c.text) <= cfg.MAX_CHUNK_CHARS for c in chunks)
    assert len(chunks) <= cfg.MAX_CHUNKS_PER_FILE


